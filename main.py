# ============================================================
# HEALTH CHECK
# ============================================================

@app.get("/")
def root():
    return {
        "status": "online",
        "service": "JARVIS AI Call Assistant",
        "model": MODEL_NAME
    }


@app.get("/health")
def health():
    return {
        "status": "healthy",
        "openai_configured": bool(API_KEY)
    }


# ============================================================
# CHAT ENDPOINT
# ============================================================

@app.post("/chat")
def chat(request: ChatRequest):

    message = request.message.strip()

    if not message:
        raise HTTPException(
            status_code=400,
            detail="Message খালি হতে পারবে না।"
        )

    try:

        answer = ask_jarvis(message)

        return {
            "success": True,
            "response": answer
        }

    except Exception as error:

        raise HTTPException(
            status_code=500,
            detail=str(error)
        )


